#!/usr/bin/env node
// Render docs/venues.md from the catalog.
//
//   npm run docs:venues
//
// Generated rather than written, for the same reason the catalog is: a
// hand-maintained table of what a chain currently supports is wrong within a
// week and nothing tells you when.

import { writeFile } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { formatUnits } from 'viem';
import { CATALOG_META, listVenues } from '../src/chains/robinhood/venues/index.js';
import { ROBINHOOD_EXPLORER } from '../src/chains/robinhood/chain.js';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const usable = listVenues({ usable: true });
const unusable = listVenues({ usable: false });

const link = (address) => `[\`${address}\`](${ROBINHOOD_EXPLORER}/address/${address})`;
const fn = (venue) => `\`${venue.launch.signature.split('(')[0]}\``;
const fee = (venue) => `${formatUnits(BigInt(venue.launch.value), 18)} ETH`;
const live = (venue) => {
	if (!venue.liveCheck) return 'not checked';
	return venue.liveCheck.ok ? 'yes' : `reverts \`${venue.liveCheck.revert || venue.liveCheck.reason}\``;
};

const lines = [
	'# Robinhood Chain launch venues',
	'',
	'<!-- Generated by tools/write-venue-docs.mjs. Run `npm run docs:venues` after a catalog rebuild. -->',
	'',
	`Learned from blocks ${CATALOG_META.window?.fromBlock}-${CATALOG_META.window?.toBlock} on ${CATALOG_META.generatedAt?.slice(0, 10)}, `,
	`across ${CATALOG_META.tokensScanned} token mints. ${usable.length} of ${usable.length + unusable.length} venues are launchable.`,
	'',
	'How this is produced, and what it does and does not guarantee:',
	'[The venue catalog](../README.md#the-venue-catalog).',
	'',
	'## Launchable',
	'',
	'`seen` is how many token launches this contract actually produced inside the',
	'window, not a ranking anyone published. `fee` is the floor observed, which',
	'excludes creator buys. `live` means a real launch, with a fresh name, symbol',
	'and salt, was executed against chain state and did not revert.',
	'',
	'| id | venue | kind | seen | fee | live | call | contract |',
	'| --- | --- | --- | ---: | --- | --- | --- | --- |',
	...usable.map((v) => `| \`${v.id}\` | ${v.label || '(unnamed)'} | ${v.kind} | ${v.observed?.launches ?? 0} | ${fee(v)} | ${live(v)} | ${fn(v)} | ${link(v.address)} |`),
	'',
	'### What each one lets you set',
	'',
	'Fields not listed keep the value from the venue\'s anchor launch.',
	'',
	'| id | fields bound to your input |',
	'| --- | --- |',
	...usable.map((v) => `| \`${v.id}\` | ${v.launch.bindings.map((b) => b.role).join(', ') || '(none: identity could not be located in the calldata)'} |`),
	'',
];

if (unusable.length) {
	lines.push(
		'## Catalogued but not launchable',
		'',
		'Published anyway: a launchpad this toolkit cannot drive is still a fact about',
		'the chain, and a silent omission looks identical to a venue that does not exist.',
		'',
		'| contract | seen | why not |',
		'| --- | ---: | --- |',
		...unusable.map((v) => `| ${link(v.address)} | ${v.observed?.launches ?? 0} | ${v.reason} |`),
		'',
	);
}

await writeFile(join(root, 'docs/venues.md'), `${lines.join('\n')}\n`);
console.log(`wrote docs/venues.md (${usable.length} launchable, ${unusable.length} not)`);
